import asyncio
from pathlib import Path
from playwright.async_api import async_playwright
ROOT=Path(__file__).resolve().parents[1]

def check(x,msg):
 if not x: raise AssertionError(msg)

async def main():
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  page=await browser.new_page(viewport={'width':1440,'height':920},device_scale_factor=1,accept_downloads=True)
  errs=[];page.on('pageerror',lambda e:errs.append(str(e)))
  html=(ROOT/'dev.html').read_text()
  for line in ['<link rel="stylesheet" href="styles.css" />','<script src="engine.js" defer></script>','<script src="demo-data.js" defer></script>','<script src="app.js" defer></script>']:
   html=html.replace(line,'')
  await page.set_content(html)
  await page.add_style_tag(content=(ROOT/'styles.css').read_text())
  for s in ['engine.js','demo-data.js','app.js']:
   await page.add_script_tag(content=(ROOT/s).read_text())
  await page.evaluate('window.dispatchEvent(new Event("DOMContentLoaded"))')
  await page.wait_for_timeout(150)
  check(await page.locator('.kpi-value').all_text_contents()==['$1,390.00','$610.00','$210.00','08'],'Overview numbers')
  check((await page.locator('.notice-icon').inner_text()).strip()=='i','Notice icon text not overwritten')
  check(await page.locator('#draft-preview').count()==0,'No stale drawer content on load')
  await page.screenshot(path=str(ROOT/'screenshots'/'dashboard.png'),full_page=True)
  print('PASS dashboard money and counts')
  # Case list and filters
  await page.locator('[data-view="cases"]').click()
  check(await page.locator('#view-cases .data-table tbody tr').count()==8,'8 cases shown')
  await page.screenshot(path=str(ROOT/'screenshots'/'cases.png'),full_page=True)
  async with page.expect_download(timeout=8000) as dl_info:
   await page.locator('[data-action="export-cases"]').click()
  dl=await dl_info.value
  check(dl.suggested_filename.endswith('.csv'),'case export file')
  print('PASS audit export')
  await page.locator('#case-search').fill('LAB-1002')
  check(await page.locator('#view-cases .data-table tbody tr').count()==1,'search result count')
  await page.locator('#case-search').fill('')
  await page.locator('#category-filter').select_option('needs_evidence')
  check(await page.locator('#view-cases .data-table tbody tr').count()==2,'category filter')
  await page.locator('#category-filter').select_option('all')
  print('PASS case filters/search')
  # Drawer and source evidence
  await page.locator('#view-cases [data-case]').first.click()
  check(await page.locator('#case-drawer').is_visible(),'drawer visible')
  check(await page.locator('#case-drawer details').count()>0,'evidence drilldown present')
  check(not await page.locator('#draft-preview').is_visible(),'Draft hidden until requested')
  await page.locator('#case-drawer details').first.locator('summary').click()
  check(await page.locator('#case-drawer details').first.get_attribute('open') is not None,'source record expanded')
  await page.screenshot(path=str(ROOT/'screenshots'/'drawer.png'),full_page=True)
  await page.locator('#copy-draft').click()
  check(await page.locator('#draft-preview').is_visible(),'reviewable follow-up draft')
  check('Billing reconciliation review' in await page.locator('#draft-text').input_value(),'follow-up content')
  await page.locator('#review-status').select_option('Investigating')
  await page.locator('#review-note').fill('Checked work evidence; reviewing price agreement')
  await page.locator('#save-review').click()
  check(not await page.locator('#case-drawer').is_visible(),'drawer closed on save')
  check(await page.get_by_text('Investigating',exact=True).count()>=1,'investigating status present')
  print('PASS case details/evidence/review')
  # Resolution is gated by documentation
  await page.locator('#view-cases [data-case]').first.click()
  await page.locator('#review-status').select_option('Resolved')
  await page.locator('#save-review').click()
  check(await page.locator('#case-drawer').is_visible(),'unverified resolved rejected')
  await page.locator('#resolution-outcome').select_option('cash_collected')
  await page.locator('#resolution-amount').fill('480.00')
  await page.locator('#resolution-reference').fill('RECEIPT-DEMO-001')
  await page.locator('#save-review').click()
  check(not await page.locator('#case-drawer').is_visible(),'documented resolution saved')
  await page.locator('[data-view="overview"]').click()
  check(await page.get_by_text('$480.00',exact=True).count()>=1,'verified outcome visible')
  check('07' in await page.locator('.kpi-value').all_text_contents(),'open queue decrement')
  print('PASS verified outcome with proof')
  # Save and restore reviewer work for the exact dataset (no silent browser storage)
  await page.locator('[data-view="cases"]').click()
  async with page.expect_download(timeout=8000) as session_info:
   await page.locator('[data-action="save-reviews"]').click()
  saved=await session_info.value
  session_path=await saved.path()
  check(saved.suggested_filename.endswith('.json'),'review session JSON saved')
  await page.locator('[data-view="sources"]').click()
  await page.locator('#reset-samples').click()
  await page.locator('[data-view="cases"]').click()
  check(await page.locator('#view-cases .data-table tbody').get_by_text('Resolved',exact=True).count()==0,'reset removes previous review state')
  await page.locator('#session-upload').set_input_files(session_path)
  await page.wait_for_timeout(80)
  check(await page.locator('#view-cases .data-table tbody').get_by_text('Resolved',exact=True).count()>=1,'exact audit review session restored')
  await page.locator('[data-view="overview"]').click()
  check(await page.get_by_text('$480.00',exact=True).count()>=1,'collections recalculated after restore')
  print('PASS audited review export and restore')
  # Data room
  await page.locator('[data-view="sources"]').click()
  check(await page.locator('.file-card').count()==5,'five data cards')
  await page.screenshot(path=str(ROOT/'screenshots'/'data_room.png'),full_page=True)
  # Fresh dataset: first custom file clears sample files
  await page.locator('#upload-work').set_input_files(str(ROOT/'samples'/'completed_work.csv'))
  check(await page.get_by_text('Not uploaded').count()>=3,'custom datasets never mix with demo')
  await page.locator('#run-data-audit').click()
  check(await page.locator('.error-panel').count()>0,'missing required inputs prevent audit')
  for kind,name in [('rates','contract_rates.csv'),('invoices','invoice_lines.csv'),('payments','payments.csv'),('adjustments','adjustments.csv')]:
   await page.locator('#upload-'+kind).set_input_files(str(ROOT/'samples'/name))
  await page.wait_for_timeout(200)
  await page.locator('#run-data-audit').click()
  check(await page.locator('.error-panel').count()==0,'five custom CSV imports validate')
  await page.locator('[data-view="overview"]').click()
  check((await page.locator('.kpi-value').first.inner_text())=='$1,390.00','imported dataset matches demo')
  print('PASS isolated CSV uploads and rerun')
  # Restore demo
  await page.locator('[data-view="sources"]').click()
  await page.locator('#reset-samples').click()
  await page.locator('[data-view="method"]').click()
  await page.screenshot(path=str(ROOT/'screenshots'/'method.png'),full_page=True)
  check(await page.locator('.method-card').count()==4,'methodology layout')
  print('PASS reset and methodology')
  # Mobile responsive
  await page.set_viewport_size({'width':390,'height':844})
  await page.locator('[data-view="overview"]').click()
  await page.wait_for_timeout(3900)
  await page.screenshot(path=str(ROOT/'screenshots'/'mobile.png'),full_page=True)
  check(await page.evaluate('document.documentElement.scrollWidth <= innerWidth+2'),'mobile no document horizontal overflow')
  await page.locator('[data-view="cases"]').click()
  check(await page.evaluate('document.documentElement.scrollWidth <= innerWidth+2'),'mobile case review no horizontal overflow')
  await page.locator('[data-view="sources"]').click()
  check(await page.evaluate('document.documentElement.scrollWidth <= innerWidth+2'),'mobile data room no horizontal overflow')
  print('PASS mobile layout')
  check(not errs,'JS errors '+repr(errs))
  print('PASS no JavaScript exceptions')
  await browser.close()

asyncio.run(main())
